"""Workspace 5: Executive Brief. AI (or rule-based) interpretation of the calculated findings, plus the 30/60/90 plan."""
import json

import streamlit as st

from ai.brief import BriefResult, generate_brief
from ai.schema import Brief
from config.settings import get_settings
from services.bundle_ui import (evidence_for, evidence_hash, get_bundle, get_brief, has_stale_brief,
                                set_brief)
from ui.components.badges import badge_html
from ui.components.cards import callout
from ui.components.html import render


def _brief_markdown(r: BriefResult) -> str:
    b: Brief = r.brief
    lines = [f"# {b.headline}", "", b.executive_summary, "", "## Top operational issues"]
    lines += [f"- **{i.title}.** {i.detail}" for i in b.top_issues]
    lines += ["", "## Root-cause hypotheses (not proven)"] + [f"- {h.hypothesis} _Evidence: {h.evidence}_" for h in b.root_cause_hypotheses]
    lines += ["", "## Automation opportunities"] + [f"- **{i.title}.** {i.detail}" for i in b.automation_opportunities]
    lines += ["", "## Business impact (estimate)", b.business_impact, "", "## Recommended actions"]
    lines += [f"- **{a.action}.** {a.rationale}" for a in b.recommended_actions]
    for title, items in (("First 30 days", b.plan_30_days), ("Days 31 to 60", b.plan_60_days), ("Days 61 to 90", b.plan_90_days)):
        lines += ["", f"## {title}"] + [f"- {x}" for x in items]
    lines += ["", "_Decision-support output. Validate with the business owners before implementation._"]
    return "\n".join(lines)


def _verification(r: BriefResult) -> None:
    v = r.validation
    if r.source == "rules":
        callout("success", "Every figure comes straight from the analysis",
                f"This brief was generated by fixed rules, not by an AI model. All {v.total} figures were checked against the findings.")
    elif v.ok:
        callout("success", f"All {v.total} figures traced to the analysis",
                "Every number the AI wrote was found in the calculated findings.")
    else:
        callout("warning", f"{len(v.unsupported)} figure(s) could not be traced to the analysis",
                f"{v.supported} of {v.total} figures were verified. Do not use these without checking them yourself: "
                f"<b>{', '.join(v.unsupported)}</b>")


def _show(r: BriefResult) -> None:
    b = r.brief
    tag = badge_html("ai") if r.source == "ai" else badge_html("metric")
    who = f"Written by {r.model}" if r.source == "ai" else "Generated from fixed rules, without AI"
    st.caption(f"{who}  |  {r.generated_at}")
    if r.fallback_reason:
        callout("info", "Rule-based brief", r.fallback_reason)
    _verification(r)

    st.markdown("### Executive process health brief")
    render(tag)
    callout("info", b.headline, b.executive_summary)

    st.markdown("### Top operational issues")
    render(badge_html("metric"))
    for i in b.top_issues:
        st.markdown(f"**{i.title}.** {i.detail}")

    if b.root_cause_hypotheses:
        st.markdown("### Root-cause hypotheses")
        render(badge_html("hypothesis" if r.source == "ai" else "inference"))
        st.caption("Possible explanations, not proven. Confirm them with the process owners.")
        for h in b.root_cause_hypotheses:
            st.markdown(f"- {h.hypothesis}  \n  *Evidence: {h.evidence}*")

    st.markdown("### Automation opportunities")
    render(tag)
    for i in b.automation_opportunities:
        st.markdown(f"**{i.title}.** {i.detail}")

    st.markdown("### Business impact")
    render(badge_html("estimate"))
    st.write(b.business_impact)

    st.markdown("### Recommended actions")
    for a in b.recommended_actions:
        st.markdown(f"- **{a.action}.** {a.rationale}")

    st.markdown("### Improvement plan")
    t30, t60, t90 = st.tabs(["First 30 days", "Days 31 to 60", "Days 61 to 90"])
    for tab, items in ((t30, b.plan_30_days), (t60, b.plan_60_days), (t90, b.plan_90_days)):
        with tab:
            for x in items:
                st.checkbox(x, key=f"plan_{abs(hash(x))}")
    if b.data_caveats:
        with st.expander("Data caveats that affect confidence"):
            for c in b.data_caveats:
                st.write(f"- {c}")

    callout("warning", "Decision support, not decisions",
            "AI and rule-based recommendations are decision-support outputs. Validate them with the business owners "
            "before implementation.")
    st.download_button("Download brief (Markdown)", _brief_markdown(r).encode("utf-8"),
                       file_name="executive_brief.md", mime="text/markdown")


def render_executive_brief() -> None:
    bundle = get_bundle()
    if bundle is None:
        callout("warning", "Complete Data Intake first",
                "The brief is written from your analysed findings. Upload data, approve the cleaned version, and "
                "confirm the process mapping to continue.")
        return

    settings = get_settings()
    evidence = evidence_for(bundle)
    ev_hash = evidence_hash(evidence)

    if settings.ai_enabled:
        callout("info", "AI layer connected",
                f"Model: <code>{settings.openrouter_model}</code>. The AI receives only the aggregated evidence pack "
                f"below, never your raw rows. Your API key stays on the server and is never shown.")
    else:
        callout("warning", "No-AI mode", "No API key is configured, so the brief is generated from fixed rules. "
                                         "Add OPENROUTER_API_KEY to your .env file to enable the AI-written version.")

    with st.expander("Exactly what is sent to the AI (evidence pack)"):
        st.caption(f"{len(json.dumps(evidence)):,} characters of aggregated findings. No raw rows, no case IDs, no file contents.")
        st.json(evidence, expanded=False)

    c1, c2, _ = st.columns([2, 2, 3])
    ai_clicked = c1.button("Generate brief with AI", type="primary", disabled=not settings.ai_enabled)
    rules_clicked = c2.button("Generate rule-based brief")
    if ai_clicked or rules_clicked:
        with st.spinner("Writing the brief..." if ai_clicked else "Building the brief..."):
            use = settings if ai_clicked else type(settings)(openrouter_api_key="")
            set_brief(ev_hash, generate_brief(evidence, use))
        st.rerun()

    result = get_brief(ev_hash)
    if result is None:
        if has_stale_brief(ev_hash):
            callout("info", "The analysis has changed", "Your simulator settings or data changed since the last brief. "
                                                        "Generate it again to reflect them.")
        return
    st.markdown("---")
    _show(result)